import zipfile
import os
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split

# 1. Unzip the dataset
zip_path = '/content/archive.zip'
extract_path = '/content/extracted_data'

with zipfile.ZipFile(zip_path, 'r') as zip_ref:
    zip_ref.extractall(extract_path)

print("Extracted files:", os.listdir(extract_path))

# Find the CSV file in the extracted files
csv_files = [f for f in os.listdir(extract_path) if f.endswith('.csv')]
if csv_files:
    df = pd.read_csv(os.path.join(extract_path, csv_files[0]))
    print(f"\nDataset loaded successfully with shape: {df.shape}")
    print("\nFirst 5 rows:")
    print(df.head())

    # Identify target column (assuming the last column if not obvious, or a categorical column)
    # For demonstration, we will pick the column with fewer unique values as target, or defaults to the last column
    target_col = df.columns[-1]
    for col in df.columns:
        if df[col].nunique() < 10:
            target_col = col
            break

    print(f"\nSelected target column for distribution and splitting: '{target_col}'")

    # 2. Split the data
    train_df, test_df = train_test_split(df, test_size=0.2, random_state=42, stratify=df[target_col] if df[target_col].nunique() > 1 and df[target_col].value_counts().min() > 1 else None)
    print(f"Data split: Train shape = {train_df.shape}, Test shape = {test_df.shape}")

    # 3. Perform EDA (Class distribution)
    class_counts = df[target_col].value_counts()
    print("\nClass Counts:")
    print(class_counts)

    # 4. Make Pie Chart
    plt.figure(figsize=(8, 8))
    plt.pie(class_counts, labels=class_counts.index, autopct='%1.1f%%', startangle=140, colors=plt.cm.Paired.colors)
    plt.title(f'Distribution of {target_col}')
    plt.axis('equal')
    plt.show()
else:
    print("No CSV file found in the zip archive to perform EDA on. Please verify the contents.")